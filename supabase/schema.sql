create policy "public write nodes" on public.knowledge_nodes for all using (true) with check (true);

drop policy if exists "public read links" on public.knowledge_links;
create policy "public read links" on public.knowledge_links for select using (true);

drop policy if exists "public write links" on public.knowledge_links;
create policy "public write links" on public.knowledge_links for all using (true) with check (true);
